#!/usr/bin/env node
// Generate docs/TEST-CATALOG.md from vitest JSON reporter + bats @test declarations.
// Usage: node tools/gen-test-catalog.mjs [--skip-vitest]
//   --skip-vitest  skip the vitest run, re-use /tmp/test-catalog-vitest.json

import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = process.cwd();
const VITEST_JSON = '/tmp/test-catalog-vitest.json';
const BATS_DIR = join(ROOT, 'scripts/camera-node/__tests__');
const OUT = join(ROOT, 'docs/TEST-CATALOG.md');

const skipVitest = process.argv.includes('--skip-vitest');

if (!skipVitest) {
  process.stderr.write('[catalog] running vitest with JSON reporter...\n');
  // execFileSync (not exec) — no shell, hard-coded args, no injection surface.
  execFileSync('npx', ['vitest', 'run', '--reporter=json', `--outputFile=${VITEST_JSON}`], {
    stdio: ['ignore', 'ignore', 'inherit'],
  });
}

const vitestData = JSON.parse(readFileSync(VITEST_JSON, 'utf8'));

// Category bucket based on the test file's path within the repo
function categorize(absPath) {
  const rel = relative(ROOT, absPath);
  if (rel.startsWith('packages/shared/')) return 'Shared';
  if (rel.startsWith('src/api/src/__tests__/routes/')) return 'API · Routes';
  if (rel.startsWith('src/api/src/__tests__/services/')) return 'API · Services';
  if (rel.startsWith('src/api/src/__tests__/middleware/')) return 'API · Middleware';
  if (rel.startsWith('src/api/src/__tests__/')) return 'API · Core';
  if (rel.startsWith('src/frontend/')) return 'Frontend';
  if (rel.startsWith('src/simulator/')) return 'Simulator';
  if (rel.startsWith('src/device/')) return 'Device';
  return 'Other';
}

const STATUS_ICON = {
  passed: 'PASS',
  failed: 'FAIL',
  skipped: 'SKIP',
  todo: 'TODO',
  pending: 'PENDING',
};

function escMd(s) {
  return String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

// ── Vitest grouping ──────────────────────────────────────────────
const byCategory = new Map();
for (const file of vitestData.testResults) {
  const cat = categorize(file.name);
  const rel = relative(ROOT, file.name);
  if (!byCategory.has(cat)) byCategory.set(cat, new Map());
  const byFile = byCategory.get(cat);
  if (!byFile.has(rel)) byFile.set(rel, []);
  for (const a of file.assertionResults) {
    byFile.get(rel).push({
      describe: a.ancestorTitles.join(' › '),
      title: a.title,
      status: a.status,
      durationMs: Math.round(a.duration ?? 0),
    });
  }
}

// ── Bats parsing ─────────────────────────────────────────────────
const batsByFile = new Map();
if (existsSync(BATS_DIR)) {
  for (const f of readdirSync(BATS_DIR)) {
    if (!f.endsWith('.bats')) continue;
    const src = readFileSync(join(BATS_DIR, f), 'utf8');
    const tests = [];
    // Matches: @test "name" {  (allows escaped quotes, single-line name)
    const re = /^@test\s+"((?:[^"\\]|\\.)*)"\s*\{/gm;
    let m;
    while ((m = re.exec(src)) !== null) {
      const name = m[1].replace(/\\"/g, '"');
      const isSkip = /# skip\b/.test(src.slice(m.index, m.index + 300));
      tests.push({ name, status: isSkip ? 'skipped' : 'passed' });
    }
    if (tests.length > 0) batsByFile.set(f, tests);
  }
}

// ── Render markdown ──────────────────────────────────────────────
const lines = [];
const totals = {
  vitest: vitestData.numTotalTests,
  vitestPassed: vitestData.numPassedTests,
  vitestFailed: vitestData.numFailedTests,
  vitestSkipped: vitestData.numPendingTests + vitestData.numTodoTests,
  batsTotal: [...batsByFile.values()].reduce((s, t) => s + t.length, 0),
  batsSkipped: [...batsByFile.values()].reduce((s, t) => s + t.filter((x) => x.status === 'skipped').length, 0),
};

lines.push('# Test Catalog');
lines.push('');
lines.push('> Auto-generated by `tools/gen-test-catalog.mjs` — do not edit manually.');
lines.push('> Regenerate with: `make test-catalog` or `node tools/gen-test-catalog.mjs`');
lines.push('');
lines.push(`**Generated**: ${new Date().toISOString().slice(0, 19).replace('T', ' ')} UTC`);
lines.push('');
lines.push('## Summary');
lines.push('');
lines.push('| Suite | Total | Passed | Failed | Skipped/Todo |');
lines.push('|---|---:|---:|---:|---:|');
lines.push(`| Vitest | ${totals.vitest} | ${totals.vitestPassed} | ${totals.vitestFailed} | ${totals.vitestSkipped} |`);
lines.push(`| Bats | ${totals.batsTotal} | ${totals.batsTotal - totals.batsSkipped} | 0 | ${totals.batsSkipped} |`);
lines.push(`| **Total** | **${totals.vitest + totals.batsTotal}** | **${totals.vitestPassed + (totals.batsTotal - totals.batsSkipped)}** | **${totals.vitestFailed}** | **${totals.vitestSkipped + totals.batsSkipped}** |`);
lines.push('');

lines.push('## Legend');
lines.push('- **PASS** — test executed and passed');
lines.push('- **FAIL** — test executed and failed');
lines.push('- **SKIP** — test was skipped (e.g., via `test.skip` or `# skip` in bats)');
lines.push('- **TODO** — placeholder test (`test.todo`)');
lines.push('- Test ID format: `<file>:<describe-chain>:<title>`');
lines.push('- "Actual" reflects the run that generated this file; re-run to refresh.');
lines.push('');

// ── Vitest sections ──────────────────────────────────────────────
const categoryOrder = ['Shared', 'API · Core', 'API · Routes', 'API · Services', 'API · Middleware', 'Frontend', 'Simulator', 'Device', 'Other'];
for (const cat of categoryOrder) {
  const byFile = byCategory.get(cat);
  if (!byFile || byFile.size === 0) continue;
  const catTotal = [...byFile.values()].reduce((s, t) => s + t.length, 0);
  lines.push(`## ${cat} (${catTotal} vitest)`);
  lines.push('');
  const sortedFiles = [...byFile.keys()].sort();
  for (const file of sortedFiles) {
    const tests = byFile.get(file);
    lines.push(`### \`${file}\` (${tests.length} tests)`);
    lines.push('');
    lines.push('| # | Test (describe › it) | Expected behavior | Actual | ms |');
    lines.push('|---:|---|---|:---:|---:|');
    tests.forEach((t, i) => {
      const idPart = t.describe ? `**${escMd(t.describe)}** › ${escMd(t.title)}` : escMd(t.title);
      const expected = escMd(t.title);
      const actual = STATUS_ICON[t.status] ?? t.status;
      lines.push(`| ${i + 1} | ${idPart} | ${expected} | ${actual} | ${t.durationMs} |`);
    });
    lines.push('');
  }
}

// ── Bats section ─────────────────────────────────────────────────
if (batsByFile.size > 0) {
  lines.push(`## Device · Camera Node (${totals.batsTotal} bats)`);
  lines.push('');
  const sortedBats = [...batsByFile.keys()].sort();
  for (const f of sortedBats) {
    const tests = batsByFile.get(f);
    lines.push(`### \`scripts/camera-node/__tests__/${f}\` (${tests.length} tests)`);
    lines.push('');
    lines.push('| # | Test name | Actual |');
    lines.push('|---:|---|:---:|');
    tests.forEach((t, i) => {
      lines.push(`| ${i + 1} | ${escMd(t.name)} | ${STATUS_ICON[t.status]} |`);
    });
    lines.push('');
  }
}

writeFileSync(OUT, lines.join('\n') + '\n');
process.stderr.write(`[catalog] wrote ${OUT} (${totals.vitest + totals.batsTotal} tests)\n`);
